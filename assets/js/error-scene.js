/* Error pages: "<code> <caption>" drawn in pixel type.
   The code and caption come from the canvas data attributes
   (data-code / data-sub), so 404, 403, 500, 503 and friends share one script. */
(function () {
    var text = document.getElementById('px404');
    if (!text || !text.getContext) return;
    var tg = text.getContext('2d');

    var FONT = {
        '0': ['01110', '10001', '10011', '10101', '11001', '10001', '01110'],
        '1': ['00100', '01100', '00100', '00100', '00100', '00100', '01110'],
        '2': ['01110', '10001', '00001', '00010', '00100', '01000', '11111'],
        '3': ['11110', '00001', '00001', '01110', '00001', '00001', '11110'],
        '4': ['10010', '10010', '10010', '11111', '00010', '00010', '00010'],
        '5': ['11111', '10000', '11110', '00001', '00001', '10001', '01110'],
        '6': ['01110', '10000', '10000', '11110', '10001', '10001', '01110'],
        '7': ['11111', '00001', '00010', '00100', '01000', '01000', '01000'],
        '8': ['01110', '10001', '10001', '01110', '10001', '10001', '01110'],
        '9': ['01110', '10001', '10001', '01111', '00001', '00001', '01110'],
        'A': ['01110', '10001', '10001', '11111', '10001', '10001', '10001'],
        'B': ['11110', '10001', '10001', '11110', '10001', '10001', '11110'],
        'C': ['01110', '10001', '10000', '10000', '10000', '10001', '01110'],
        'D': ['11110', '10001', '10001', '10001', '10001', '10001', '11110'],
        'E': ['11111', '10000', '10000', '11110', '10000', '10000', '11111'],
        'F': ['11111', '10000', '10000', '11110', '10000', '10000', '10000'],
        'G': ['01110', '10001', '10000', '10111', '10001', '10001', '01111'],
        'H': ['10001', '10001', '10001', '11111', '10001', '10001', '10001'],
        'I': ['11111', '00100', '00100', '00100', '00100', '00100', '11111'],
        'K': ['10001', '10010', '10100', '11000', '10100', '10010', '10001'],
        'L': ['10000', '10000', '10000', '10000', '10000', '10000', '11111'],
        'M': ['10001', '11011', '10101', '10101', '10001', '10001', '10001'],
        'N': ['10001', '11001', '10101', '10011', '10001', '10001', '10001'],
        'O': ['01110', '10001', '10001', '10001', '10001', '10001', '01110'],
        'P': ['11110', '10001', '10001', '11110', '10000', '10000', '10000'],
        'R': ['11110', '10001', '10001', '11110', '10100', '10010', '10001'],
        'S': ['01111', '10000', '10000', '01110', '00001', '00001', '11110'],
        'T': ['11111', '00100', '00100', '00100', '00100', '00100', '00100'],
        'U': ['10001', '10001', '10001', '10001', '10001', '10001', '01110'],
        'V': ['10001', '10001', '10001', '10001', '10001', '01010', '00100'],
        'W': ['10001', '10001', '10001', '10101', '10101', '11011', '10001'],
        'Y': ['10001', '10001', '01010', '00100', '00100', '00100', '00100'],
        ' ': ['00000', '00000', '00000', '00000', '00000', '00000', '00000']
    };
    var BIG = 4, BIG_GAP = 8, LINE_GAP = 7, PAD = 2;
    var CODE = (text.getAttribute('data-code') || '404').toUpperCase().replace(/[^A-Z0-9]/g, '') || '404';
    var small = (text.getAttribute('data-sub') || 'PAGE NOT FOUND').toUpperCase().replace(/[^A-Z0-9 ]/g, '') || 'PAGE NOT FOUND';
    var bigW = CODE.length * 5 * BIG + (CODE.length - 1) * BIG_GAP, smallW = small.length * 6 - 1;
    var GW = Math.max(bigW, smallW) + PAD * 2 + 8, GH = 7 * BIG + LINE_GAP + 7 + PAD * 2;
    text.width = GW; text.height = GH;
    tg.fillStyle = '#0A0A0A';

    // big code: each font pixel is a BIG x BIG block
    var bx = Math.floor((GW - bigW) / 2);
    CODE.split('').forEach(function (ch, i) {
        (FONT[ch] || FONT[' ']).forEach(function (row, ry) {
            for (var rx = 0; rx < 5; rx++) if (row[rx] === '1')
                tg.fillRect(bx + i * (5 * BIG + BIG_GAP) + rx * BIG, PAD + ry * BIG, BIG, BIG);
        });
    });
    // caption underneath, one canvas pixel per font pixel
    var sx0 = Math.floor((GW - smallW) / 2), sy0 = PAD + 7 * BIG + LINE_GAP;
    small.split('').forEach(function (ch, i) {
        (FONT[ch] || FONT[' ']).forEach(function (row, ry) {
            for (var rx = 0; rx < 5; rx++) if (row[rx] === '1') tg.fillRect(sx0 + i * 6 + rx, sy0 + ry, 1, 1);
        });
    });
})();
