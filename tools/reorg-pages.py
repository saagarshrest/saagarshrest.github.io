#!/usr/bin/env python3
"""Group root pages into folders by type and rewrite every reference.

GitHub Pages cannot send server redirects, so old URLs are handled by a small
script in 404.html: it looks the requested path up in REDIRECTS and forwards
the visitor with location.replace(). Re-running this script is safe.
"""
import os, re, subprocess, glob, json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

GROUPS = {
    'work': ['Casestudy', 'Casedetail', 'Casedetailofficiti', 'Casedetailramroparts',
             'Shiftcarecase', 'Clients', 'Design', 'DesignSystem', 'UXAudit'],
    'products': ['Products', 'Commando', 'DesignSystemCreator', 'ImageCleaner',
                 'KathmanduShadows'],
    'about': ['Resume', 'Photos'],
    # PP-period-tracker and TandC-Period-tracker deliberately stay at the root.
    'legal': ['privacy', 'terms', 'cookie-policy', 'disclaimer', 'accessibility'],
    'pages': ['contact', 'faq', 'archive', 'sitemap-page', 'thank-you'],
    'errors': ['403', '500', '503', 'error', 'offline'],
    'Articles': ['Article'],
}
MOVES = {f'{n}.html': f'{d}/{n}.html' for d, names in GROUPS.items() for n in names}

# ---------------------------------------------------------------- 1. moves
for old, new in MOVES.items():
    if os.path.exists(old):
        os.makedirs(os.path.dirname(new), exist_ok=True)
        subprocess.run(['git', 'mv', old, new], check=True)
        print('moved', old, '->', new)

# ---------------------------------------------------------------- 2. references
SELF = os.path.relpath(os.path.abspath(__file__), ROOT)
files = [f for f in subprocess.run(['git', 'ls-files'], capture_output=True, text=True,
                                   check=True).stdout.splitlines()
         if f != SELF and f != 'tools/reorg-assets.py'
         and re.search(r'\.(html|js|py|xml|txt|md|webmanifest)$', f)]

subs = []
for old, new in MOVES.items():
    o = re.escape(old)
    # root-absolute links: "/x.html", '/x.html', (/x.html, `/x.html`, Disallow: /x.html
    subs.append((re.compile(r'(?<=["\'(`\s])/' + o + r'(?![\w-])'), '/' + new))
    # absolute URLs: canonical, og:url, sitemap.xml, feed.xml, security.txt
    subs.append((re.compile(r'(saagarshrest\.com\.np)/' + o + r'(?![\w-])'), r'\1/' + new))
    # build-pages.py output keys
    subs.append((re.compile(r"PAGES\['" + o + r"'\]"), f"PAGES['{new}']"))

for f in files:
    s = open(f, encoding='utf-8').read()
    t = s
    for rx, rep in subs:
        t = rx.sub(rep, t)
    if t != s:
        open(f, 'w', encoding='utf-8').write(t)
        print('rewrote', f)

# ---------------------------------------------------------------- 3. 404 redirects
REDIRECTS = {'/' + o: '/' + n for o, n in MOVES.items()}
script = ('<script>/* old-url-redirects: generated by tools/reorg-pages.py */\n'
          '(function () {\n'
          '    var map = ' + json.dumps(REDIRECTS, separators=(',', ':')) + ';\n'
          '    var p = decodeURIComponent(location.pathname), k;\n'
          '    for (k in map) if (k.toLowerCase() === p.toLowerCase()) {\n'
          '        location.replace(map[k] + location.search + location.hash);\n'
          '        return;\n'
          '    }\n'
          '})();\n'
          '</script>\n')
s = open('404.html', encoding='utf-8').read()
s = re.sub(r'<script>/\* old-url-redirects.*?</script>\n', '', s, flags=re.S)
s = s.replace('<head>\n', '<head>\n' + script, 1)
open('404.html', 'w', encoding='utf-8').write(s)
print('wrote redirect map into 404.html (%d entries)' % len(REDIRECTS))
